"""Single entry point: build DB -> data-quality checks -> queries -> report.

Usage:
    python -m src.pipeline              # full run
    python -m src.pipeline --powerbi    # also export mart CSVs for Power BI
"""
from __future__ import annotations

import argparse
import time

from src.build_db import build_database, table_row_counts
from src.config import DB_PATH, RAW_DIR, REPORTS_DIR
from src.export_powerbi import export_mart
from src.quality import assert_no_errors, run_checks, to_markdown
from src.queries import run_all, write_catalogue
from src.report import build_figures, write_executive_summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--powerbi", action="store_true", help="export mart CSVs to powerbi/data/")
    args = parser.parse_args()
    t0 = time.perf_counter()

    con = build_database(RAW_DIR, DB_PATH)
    counts = table_row_counts(con)
    print("[1/4] mart built:", ", ".join(f"{t}={n:,}" for t, n in counts.items()))

    checks = run_checks(con)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "data_quality.md").write_text(
        "# Data-quality check results\n\nGenerated by `python -m src.pipeline` "
        "(SQL in `sql/checks/data_quality.sql`).\n\n" + to_markdown(checks), encoding="utf-8")
    assert_no_errors(checks)
    print(f"[2/4] data quality: {(checks.status == 'PASS').sum()} pass, "
          f"{(checks.status == 'WARN').sum()} warn, {(checks.status == 'FAIL').sum()} fail")

    results = run_all(con)
    write_catalogue(results)
    print(f"[3/4] {len(results)} analytical queries run -> reports/query_results, docs/QUERIES.md")

    figures = build_figures(con, results)
    write_executive_summary(results, figures)
    print(f"[4/4] {len(figures)} figures + reports/EXECUTIVE_SUMMARY.md")

    if args.powerbi:
        export_mart(con)
        print("      mart CSVs exported to powerbi/data/")
    con.close()
    print(f"Pipeline finished in {time.perf_counter() - t0:.1f}s")


if __name__ == "__main__":
    main()
