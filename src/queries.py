"""Run the analytical SQL queries and publish their real results.

Each file in ``sql/analysis/`` starts with a metadata header::

    -- title: ...
    -- question: ...
    -- technique: ...
    -- insight: ...        (one or more lines, written after reading the result)

``run_all`` executes every query against the mart, saves the full result as
CSV in ``reports/query_results/`` and ``write_catalogue`` renders
``docs/QUERIES.md`` (question, SQL, result snippet, insight) from those results,
so the documentation can never drift from what the SQL returns.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, field
from pathlib import Path

import duckdb
import pandas as pd

from src.config import ANALYSIS_DIR, QUERY_RESULTS_DIR, ROOT

HEADER_RE = re.compile(r"^--\s*(title|question|technique|note|insight):\s*(.*)$")


@dataclass
class Query:
    """An analytical query file plus its parsed metadata."""

    path: Path
    title: str = ""
    question: str = ""
    technique: str = ""
    note: str = ""
    insight: list[str] = field(default_factory=list)

    @property
    def name(self) -> str:
        return self.path.stem

    @property
    def sql(self) -> str:
        return self.path.read_text(encoding="utf-8")

    @property
    def body(self) -> str:
        """SQL without the metadata header (comments inside the query are kept)."""
        lines = self.sql.splitlines()
        return "\n".join(l for l in lines if not HEADER_RE.match(l)).strip()


def parse_query(path: Path) -> Query:
    """Read the ``-- key: value`` header of an analysis SQL file."""
    q = Query(path=path)
    for line in path.read_text(encoding="utf-8").splitlines():
        m = HEADER_RE.match(line)
        if not m:
            continue
        key, value = m.group(1), m.group(2).strip()
        if key == "insight":
            q.insight.append(value)
        else:
            setattr(q, key, value)
    return q


def list_queries(folder: Path = ANALYSIS_DIR) -> list[Query]:
    """All analysis queries, in file-name order."""
    return [parse_query(p) for p in sorted(folder.glob("*.sql"))]


def run_query(con: duckdb.DuckDBPyConnection, query: Query) -> pd.DataFrame:
    """Execute one analysis query and return the result."""
    return con.execute(query.sql).df()


def run_all(con: duckdb.DuckDBPyConnection,
            out_dir: Path | None = QUERY_RESULTS_DIR) -> dict[str, pd.DataFrame]:
    """Run every query; optionally save each result as CSV."""
    results: dict[str, pd.DataFrame] = {}
    if out_dir is not None:
        out_dir.mkdir(parents=True, exist_ok=True)
    for q in list_queries():
        df = run_query(con, q)
        results[q.name] = df
        if out_dir is not None:
            df.to_csv(out_dir / f"{q.name}.csv", index=False)
    return results


def _fmt(value: object) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return ""
    if isinstance(value, pd.Timestamp):
        return value.strftime("%Y-%m-%d")
    if isinstance(value, float):
        if value.is_integer() and abs(value) >= 1000:
            return f"{value:,.0f}"
        return f"{value:,.2f}".rstrip("0").rstrip(".") if abs(value) < 1000 else f"{value:,.1f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def df_to_markdown(df: pd.DataFrame, max_rows: int | None = None) -> str:
    """Minimal Markdown table renderer (no extra dependency)."""
    shown = df if max_rows is None else df.head(max_rows)
    header = "| " + " | ".join(map(str, shown.columns)) + " |"
    sep = "|" + "|".join("---:" if pd.api.types.is_numeric_dtype(shown[c]) else "---"
                         for c in shown.columns) + "|"
    rows = ["| " + " | ".join(_fmt(v) for v in row) + " |"
            for row in shown.itertuples(index=False)]
    out = "\n".join([header, sep, *rows])
    if max_rows is not None and len(df) > max_rows:
        out += f"\n\n*First {max_rows} of {len(df)} rows - full result in `reports/query_results/`.*"
    return out


def write_catalogue(results: dict[str, pd.DataFrame],
                    out_path: Path = ROOT / "docs" / "QUERIES.md",
                    max_rows: int = 20) -> Path:
    """Render the query catalogue (question, SQL, real result, insight)."""
    parts = [
        "# Analytical query catalogue",
        "",
        "Generated by `python -m src.pipeline` from the SQL files in `sql/analysis/`. "
        "Every table below is the real output of the query on the Olist mart "
        "(reporting period 2017-01 to 2018-08, valid sales only, revenue = item price in BRL, "
        "freight excluded).",
        "",
    ]
    queries = list_queries()
    parts.append("| # | Query | Business question |")
    parts.append("|---|---|---|")
    for q in queries:
        anchor = re.sub(r"[^a-z0-9 -]", "", f"{q.name[:2]} {q.title}".lower()).replace(" ", "-")
        parts.append(f"| {q.name[:2]} | [{q.title}](#{anchor}) | {q.question} |")
    parts.append("")
    for q in queries:
        rel = q.path.relative_to(ROOT).as_posix()
        parts += [
            f"## {q.name[:2]} {q.title}",
            "",
            f"**Business question.** {q.question}",
            "",
            f"**Technique.** {q.technique}" + (f" *Note: {q.note}*" if q.note else ""),
            "",
            f"<details><summary>SQL (<code>{rel}</code>)</summary>",
            "",
            "```sql",
            q.body,
            "```",
            "",
            "</details>",
            "",
            "**Result**",
            "",
            df_to_markdown(results[q.name], max_rows=max_rows),
            "",
        ]
        if q.insight:
            parts += ["**Insight.** " + " ".join(q.insight), ""]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(parts), encoding="utf-8")
    return out_path
